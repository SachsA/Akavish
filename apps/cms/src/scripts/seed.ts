// ─── Find-or-create helpers ────────────────────────────────────────────────

async function findIdBySlug(
  payload: Payload,
  collection: 'authors' | 'games' | 'tags' | 'articles',
  slug: string,
): Promise<ID | null> {
  const res = await payload.find({
    collection,
    where: { slug: { equals: slug } },
    limit: 1,
    depth: 0,
  })
  const id = res.docs[0]?.id
  return id == null ? null : Number(id)
}

// ─── Run ───────────────────────────────────────────────────────────────────

const run = async () => {
  assertLocalDatabase()

  const r2Enabled = Boolean(process.env.R2_BUCKET)
  const uploadCovers = !r2Enabled || withImages

  console.log('[seed] booting Payload…')
  const payload = await getPayload({ config })

  // Admin — only on an empty users table, never touches existing accounts.
  const users = await payload.count({ collection: 'users' })
  if (users.totalDocs === 0) {
    const email = process.env.SEED_ADMIN_EMAIL || 'admin@akavish.test'
    const password = process.env.SEED_ADMIN_PASSWORD || 'akavish-local'
    await payload.create({ collection: 'users', data: { email, password } })
    console.log(`[seed] admin created → ${email} / ${password}`)
  } else {
    console.log(`[seed] ${users.totalDocs} user(s) already exist — admin left untouched`)
  }

  // Author
  let authorId = await findIdBySlug(payload, 'authors', AUTHOR.slug)
  if (!authorId) {
    authorId = Number((await payload.create({ collection: 'authors', data: AUTHOR })).id)
  }

  // Games
  const gameIds = new Map<string, ID>()
  for (const game of GAMES) {
    let id = await findIdBySlug(payload, 'games', game.slug)
    if (!id) {
      const doc = await payload.create({
        collection: 'games',
        data: { ...game, platform: [...game.platform], genre: [...game.genre] },
      })
      id = Number(doc.id)
    }
    gameIds.set(game.slug, id)
  }

  // Tags
  const tagIds = new Map<string, ID>()
  for (const tag of TAGS) {
    let id = await findIdBySlug(payload, 'tags', tag.slug)
    if (!id) id = Number((await payload.create({ collection: 'tags', data: { ...tag } })).id)
    tagIds.set(tag.slug, id)
  }

  if (!uploadCovers) {
    console.log(
      `[seed] R2_BUCKET is set (${process.env.R2_BUCKET}) — skipping cover images so sample\n` +
        '       files don’t land in a real bucket. Pass --with-images to upload them anyway.',
    )
  }

  // Articles — staggered a few hours apart so "newest first" means something.
  let created = 0
  const now = Date.now()
  for (const [index, article] of ARTICLES.entries()) {
    if (await findIdBySlug(payload, 'articles', article.slug)) continue

    let coverImage: ID | undefined
    if (uploadCovers) {
      const data = await coverPng(article.title.split(':')[0].slice(0, 26), ...article.cover)
      const media = await payload.create({
        collection: 'media',
        data: { alt: `Illustration for "${article.title}"` },
        file: {
          data,
          mimetype: 'image/png',
          name: `seed-${article.slug}.png`,
          size: data.length,
        },
      })
      coverImage = Number(media.id)
    }

    await payload.create({
      collection: 'articles',
      data: {
        title: article.title,
        slug: article.slug,
        excerpt: article.excerpt,
        content: richText(article.body),
        category: article.category,
        status: 'published',
        _status: 'published',
        publishedAt: new Date(now - index * 5 * 60 * 60 * 1000).toISOString(),
        author: authorId,
        game: article.game ? gameIds.get(article.game) : undefined,
        tags: article.tags.map((slug) => tagIds.get(slug)).filter((id): id is ID => id !== undefined),
        coverImage,
        featured: article.featured ?? false,
      },
    })
    created += 1
  }

  console.log(
    `[seed] done — ${created} article(s) created, ${ARTICLES.length - created} already there.`,
  )
  if (process.env.MEILISEARCH_HOST) {
    console.log('[seed] Meilisearch is configured: run `pnpm reindex:search` to index them.')
  }
  process.exit(0)
}

run().catch((err) => {
  console.error('[seed] failed:', err)
  process.exit(1)
})
