/**
 * Seed a LOCAL database with an admin user and sample content, so a fresh
 * `docker compose up -d` + `pnpm migrate` gives a usable CMS and a homepage that
 * actually shows its layout (lead story, top stories, one section per category).
 *
 * Run with:  pnpm seed                (from apps/cms, or from the repo root)
 *            pnpm seed --with-images  (also upload covers when R2 is configured)
 *
 * Safe to re-run: everything is looked up by slug / email first, and only what's
 * missing is created. Nothing existing is modified or deleted.
 *
 * Local only: refuses to run unless DATABASE_URL points at localhost — sample
 * articles about made-up games must never reach production.
 *
 * Admin credentials: SEED_ADMIN_EMAIL / SEED_ADMIN_PASSWORD from apps/cms/.env,
 * defaulting to admin@akavish.test / akavish-local. Only created when the
 * database has no user yet.
 */
import 'dotenv/config'
import { getPayload, type Payload } from 'payload'
import sharp from 'sharp'
import config from '../payload.config'
// No import from '../payload-types': that file is generated and gitignored, so
// CI type-checks without it. The few types needed are spelled out here.
// Postgres ids are numbers; without the generated types Payload reports them as
// `number | string`, so every id goes through Number() to type-check both ways.
type ID = number
type Category = 'news' | 'leak' | 'review' | 'preview' | 'conference' | 'esport'

const LOCAL_HOSTS = new Set(['localhost', '127.0.0.1', '::1', '[::1]', 'host.docker.internal'])

const args = process.argv.slice(2)
const withImages = args.includes('--with-images')

// ─── Guards ────────────────────────────────────────────────────────────────

function assertLocalDatabase(): void {
  const raw = process.env.DATABASE_URL
  if (!raw) {
    console.error('[seed] ❌ DATABASE_URL is not set (apps/cms/.env).')
    process.exit(1)
  }
  let host: string
  try {
    host = new URL(raw).hostname
  } catch {
    console.error('[seed] ❌ DATABASE_URL is not a valid URL.')
    process.exit(1)
  }
  if (!LOCAL_HOSTS.has(host)) {
    console.error(
      `[seed] ❌ Refusing to seed "${host}": this script only runs against a local database.\n` +
        '       Sample articles about made-up games must never reach production.',
    )
    process.exit(1)
  }
}

// ─── Lexical helpers ───────────────────────────────────────────────────────
// Minimal Lexical JSON — the same shape the admin editor saves.

type Block = string | { h2: string }

const textNode = (text: string) => ({
  type: 'text',
  text,
  format: 0,
  style: '',
  mode: 'normal',
  detail: 0,
  version: 1,
})

function richText(blocks: Block[]) {
  const children = blocks.map((block) =>
    typeof block === 'string'
      ? {
          type: 'paragraph',
          format: '',
          indent: 0,
          version: 1,
          direction: 'ltr',
          textFormat: 0,
          textStyle: '',
          children: [textNode(block)],
        }
      : {
          type: 'heading',
          tag: 'h2',
          format: '',
          indent: 0,
          version: 1,
          direction: 'ltr',
          children: [textNode(block.h2)],
        },
  )
  return {
    root: { type: 'root', format: '' as const, indent: 0, version: 1, direction: 'ltr' as const, children },
  }
}

// ─── Cover images ──────────────────────────────────────────────────────────
// Generated on the fly (sharp is already a CMS dependency) so the repo carries
// no binary fixtures. 1600×900 = the 16:9 the site uses for covers.

const escapeXml = (s: string) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

async function coverPng(label: string, from: string, to: string): Promise<Buffer> {
  const svg = `
<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="900" viewBox="0 0 1600 900">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${from}"/>
      <stop offset="1" stop-color="${to}"/>
    </linearGradient>
  </defs>
  <rect width="1600" height="900" fill="url(#g)"/>
  <circle cx="1300" cy="180" r="260" fill="#ffffff" fill-opacity="0.06"/>
  <circle cx="220" cy="760" r="340" fill="#000000" fill-opacity="0.18"/>
  <text x="96" y="790" font-family="Helvetica, Arial, sans-serif" font-size="96"
        font-weight="700" fill="#ffffff" fill-opacity="0.92">${escapeXml(label)}</text>
</svg>`
  return sharp(Buffer.from(svg)).png().toBuffer()
}

